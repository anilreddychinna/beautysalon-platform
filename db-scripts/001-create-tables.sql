create extension if not exists pgcrypto;

create type service_category as enum ('hair', 'skin', 'nails', 'special');
create type payment_method as enum ('cash', 'card', 'upi');
create type user_role as enum ('Admin', 'Manager');
create type customer_gender as enum ('Female', 'Male', 'Other');

create table shops (
  id uuid primary key default gen_random_uuid(),
  name text not null check (char_length(name) between 1 and 40),
  address text not null check (char_length(address) between 1 and 80),
  phone text not null,
  email text not null,
  logo text not null default 'logo.png',
  created_at timestamptz not null default now()
);

create table users (
  id uuid primary key default gen_random_uuid(),
  username text not null unique,
  password_hash text not null,
  name text not null,
  role user_role not null,
  created_at timestamptz not null default now()
);

create table customers (
  id uuid primary key default gen_random_uuid(),
  customer_number integer generated by default as identity unique,
  name text not null check (char_length(name) between 1 and 20),
  phone text not null unique,
  gender customer_gender,
  notes text not null default '',
  created_at timestamptz not null default now()
);

create table services (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  category service_category not null,
  price numeric(12, 2) not null check (price >= 0),
  minutes integer not null check (minutes >= 1),
  active boolean not null default true,
  color text
);

create table staff (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  commission_percent numeric(5, 2) check (commission_percent between 0 and 100),
  active boolean not null default true
);

create table bills (
  id uuid primary key default gen_random_uuid(),
  bill_number text not null check (bill_number ~ '^[0-9]{1,5}$'),
  business_date date not null,
  customer_id uuid not null references customers (id),
  customer_name text not null,
  customer_phone text not null,
  subtotal numeric(12, 2) not null check (subtotal >= 0),
  discount numeric(12, 2) not null default 0 check (discount >= 0),
  tax_percent numeric(5, 2) not null default 0 check (tax_percent >= 0),
  tax_amount numeric(12, 2) not null default 0 check (tax_amount >= 0),
  total numeric(12, 2) not null check (total >= 0),
  payment_method payment_method not null,
  created_at timestamptz not null default now(),
  cancelled_at timestamptz
);

create unique index bills_active_bill_number
  on bills (bill_number)
  where cancelled_at is null;

create table bill_lines (
  id uuid primary key default gen_random_uuid(),
  bill_id uuid not null references bills (id) on delete cascade,
  service_id uuid not null references services (id),
  service_name text not null,
  category service_category not null,
  price numeric(12, 2) not null check (price >= 0),
  minutes integer not null check (minutes >= 1),
  staff_id uuid not null references staff (id),
  staff_name text not null,
  commission_percent numeric(5, 2) check (commission_percent between 0 and 100),
  quantity integer not null check (quantity >= 1),
  line_total numeric(12, 2) not null check (line_total >= 0)
);

create table day_closes (
  business_date date primary key,
  cash_counted numeric(12, 2) not null check (cash_counted >= 0),
  note text not null default '',
  closed_at timestamptz not null default now()
);
