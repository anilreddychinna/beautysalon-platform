-- Fresh setup for the salon database.
-- Run this once in the Supabase SQL Editor. It replaces db-scripts 001 through 006.
--
-- This deletes salon tables, bills, customers, services, staff, and every
-- login whose email ends with @salon.local, then creates them again.
--
-- After it finishes, sign in as:
--   admin / admin123
--   manager / manager123

create extension if not exists pgcrypto;

-- Remove the previous salon objects so this script can run on a used database.
do $$
declare
  fn record;
begin
  for fn in
    select p.oid::regprocedure as signature
    from pg_proc p
    join pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'public'
      and p.proname in ('list_staff_users', 'create_staff_login', 'seed_staff_login', 'is_admin')
  loop
    execute 'drop function if exists ' || fn.signature || ' cascade';
  end loop;
end $$;

